#!/usr/bin/env node

/**
 * 紹介ページ（GitHub Pages）の言語別静的生成
 *
 *   node scripts/build-landing.mjs          # 各ページを正規化し en/ 配下を生成
 *   node scripts/build-landing.mjs --check  # 生成結果とコミット済みファイルの差分を検査（CI 用、書き込みなし）
 *
 * ## 何をするか
 *
 * {@link PAGES} の各ページ（`index.html` = ランディング、`sample-data/index.html` = サンプルデータ）は
 * そのページの唯一のソースであり、同時に日本語ページでもある。
 * ページ内の `translations`（en / ja 辞書）と `data-i18n*` 属性を読み取り、
 *
 *   1. ソースに **日本語** 辞書を静的に適用する（`<html lang="ja">`、title / description /
 *      og:* / canonical / hreflang / JSON-LD / 言語ボタンの状態）。この処理は冪等で、
 *      既に日本語化されたソースに再適用しても変化しない。
 *   2. 同じソースから **英語** 辞書を適用したページを `en/` 配下に生成する（`en/index.html`、
 *      `en/sample-data/index.html`）。相対 URL は生成先から解決できるよう書き換える。
 *      ページへのリンク（`sample-data/`、`../#about` など）は同じ言語のページを、それ以外
 *      （assets/… api_doc/ README.md、CSS の url()）は共有のファイルを指す（{@link rewriteRelativeUrl}）。
 *
 * これにより検索エンジンは JavaScript を実行せずに各言語の内容・lang・canonical・hreflang を
 * 読める。`?lang=` クエリによる旧リンクは、ページ内 JS が対応する静的ページへ置き換える。
 *
 * ## 編集ルール
 *
 * - 文言は各ソース内の `translations` 辞書を編集する（マークアップ側の文字列は
 *   このスクリプトが辞書で上書きするため、辞書に無い変更は失われる）。
 * - `en/` 配下は生成物。直接編集しない。
 * - 編集後は `npm run build:site` を実行し、生成物もコミットする。CI は `--check` で差分を検査する。
 *
 * このモジュールは `import` からも使え、`buildLandingPages()` は書き込みせずに
 * 生成結果を返す（tests/landing-i18n.test.ts が利用）。
 *
 * ORPHE-INSOLE.js の scripts/build-landing.js を ESM に移植したもの。
 */

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE_FILE = 'index.html';
export const SITE_URL = 'https://orphe-oss.github.io/ORPHE-CORE-INSOLE.js/';

/** 言語別に生成するページ。source は日本語ページ兼ソース、path はサイト内の URL パス。 */
export const PAGES = [
  { source: SOURCE_FILE, path: '' },
  { source: 'sample-data/index.html', path: 'sample-data/' },
];

/** 言語ごとの配信設定。ja が既定（/ と x-default）。dir は生成先の接頭辞。 */
export const LANGUAGES = {
  ja: { dir: '', locale: 'ja_JP', alternateLocale: 'en_US' },
  en: { dir: 'en/', locale: 'en_US', alternateLocale: 'ja_JP' },
};

export function outputFile(page, language) {
  return LANGUAGES[language].dir + page.source;
}

export function pageUrl(page, language) {
  return SITE_URL + LANGUAGES[language].dir + page.path;
}

function relativeDirectory(fromFile, toDirectory) {
  const fromDir = path.posix.dirname(fromFile);
  const relative = path.posix.relative(fromDir === '.' ? '' : fromDir, toDirectory === '' ? '.' : toDirectory);
  return relative === '' ? './' : relative + '/';
}

/** 言語ボタンの移動先（from 言語のページから見た to 言語の同じページ）。 */
export function languageButtonHref(page, from, to) {
  return relativeDirectory(outputFile(page, from), LANGUAGES[to].dir + page.path);
}

export function generatedNotice(source) {
  return `<!-- Generated by scripts/build-landing.mjs from ${source}. Do not edit directly; edit ${source} and run \`npm run build:site\`. -->\n`;
}

export const GENERATED_NOTICE = generatedNotice(SOURCE_FILE);

function escapeText(value) {
  return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function escapeAttribute(value) {
  return escapeText(value).replace(/"/g, '&quot;');
}

/** ページ内の `const translations = {...};` を評価して辞書を得る。 */
function extractTranslations(html, source = SOURCE_FILE) {
  const match = html.match(/\n {4}const translations = (\{[\s\S]*?\n {4}\});\n/);
  if (!match) throw new Error('translations object not found in ' + source);
  const translations = vm.runInNewContext('(' + match[1] + ')', {}, { timeout: 1000 });
  for (const language of Object.keys(LANGUAGES)) {
    if (!translations[language]) throw new Error(`translations.${language} is missing`);
    for (const key of ['metaTitle', 'metaDescription']) {
      if (typeof translations[language][key] !== 'string') {
        throw new Error(`translations.${language}.${key} must be a string`);
      }
    }
  }
  return translations;
}

/**
 * `<tag … attr="key" …>…</tag>` の内容を辞書値で置き換える。
 * 同名タグの入れ子は想定しない（検出したら例外）。辞書に無いキーは元の内容を残す。
 */
function replaceElementContents(html, attr, strings, render, missing) {
  const open = new RegExp(`<([a-zA-Z][\\w-]*)((?:\\s[^<>]*?)?\\s${attr}="([^"]+)"[^<>]*)>`, 'g');
  let out = '';
  let pos = 0;
  let m;
  while ((m = open.exec(html)) !== null) {
    const [tag, , key] = [m[1], m[2], m[3]];
    const openEnd = m.index + m[0].length;
    const closeTag = `</${tag}>`;
    const closeIdx = html.indexOf(closeTag, openEnd);
    if (closeIdx < 0) throw new Error(`no closing ${closeTag} for ${attr}="${key}"`);
    const inner = html.slice(openEnd, closeIdx);
    if (new RegExp(`<${tag}[\\s>]`).test(inner)) {
      throw new Error(`nested <${tag}> inside ${attr}="${key}" is not supported`);
    }
    const value = strings[key];
    if (value === undefined) missing.push(key);
    out += html.slice(pos, openEnd) + (value === undefined ? inner : render(value)) + closeTag;
    pos = closeIdx + closeTag.length;
    open.lastIndex = pos;
  }
  return out + html.slice(pos);
}

/** `data-i18n-aria-label="key"` を持つタグの aria-label 属性を辞書値にする。 */
function replaceAriaLabels(html, strings, missing) {
  return html.replace(/<([a-zA-Z][\w-]*)((?:\s[^<>]*?)?\sdata-i18n-aria-label="([^"]+)"[^<>]*)>/g, (whole, tag, attrs, key) => {
    const value = strings[key];
    if (value === undefined) {
      missing.push(key);
      return whole;
    }
    const escaped = escapeAttribute(value);
    const nextAttrs = /\saria-label="[^"]*"/.test(attrs)
      ? attrs.replace(/\saria-label="[^"]*"/, ` aria-label="${escaped}"`)
      : `${attrs} aria-label="${escaped}"`;
    return `<${tag}${nextAttrs}>`;
  });
}

function setMetaContent(html, selector, value) {
  const re = new RegExp(`(<meta ${selector}\\s+content=")([^"]*)(")`);
  if (!re.test(html)) throw new Error(`meta not found: ${selector}`);
  return html.replace(re, `$1${escapeAttribute(value)}$3`);
}

function setLinkHref(html, selector, href) {
  const re = new RegExp(`(<link ${selector}\\s+href=")([^"]*)(")`);
  if (!re.test(html)) throw new Error(`link not found: ${selector}`);
  return html.replace(re, `$1${href}$3`);
}

function replaceOnce(html, re, replacement, label) {
  if (!re.test(html)) throw new Error(`${label} not found`);
  return html.replace(re, replacement);
}

/**
 * ソース（日本語ページ）に書かれた相対 URL を、language の生成先から同じものを指す URL にする。
 *
 * - 言語別のページ（{@link PAGES}）へのリンクは、同じ言語のページを指す（`sample-data/` → /en/ からは `sample-data/`）
 * - それ以外（画像・CSS・README・api_doc/ など）は言語で共有するファイルを指す（/en/ からは `../assets/…`）
 *
 * スキーム付き・`//`・`/`・`#` で始まる URL と、ソースと生成先が同じ場合は変更しない。
 */
export function rewriteRelativeUrl(url, page, language) {
  const output = outputFile(page, language);
  if (output === page.source || url === '' || /^(?:[a-z][a-z0-9+.-]*:|\/\/|\/|#)/i.test(url)) return url;
  const [, pathPart, suffix] = url.match(/^([^?#]*)(.*)$/);
  if (pathPart === '') return url;
  const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(page.source), pathPart)).replace(/\/+$/, '');
  const isDirectory = /(?:^|\/)\.{0,2}$/.test(pathPart);
  let target = resolved === '.' || resolved === '' ? '' : resolved + (isDirectory ? '/' : '');
  if (PAGES.some((p) => p.path === target || p.source === target)) target = LANGUAGES[language].dir + target;
  if (isDirectory) return relativeDirectory(output, target) + suffix;
  const outputDir = path.posix.dirname(output);
  return path.posix.relative(outputDir === '.' ? '' : outputDir, target) + suffix;
}

function rewriteRelativeUrls(html, page, language) {
  const rewrite = (url) => rewriteRelativeUrl(url, page, language);
  // 属性名の直前が空白のものだけを対象にする（data-lang-href などは対象外）
  return html
    .replace(/(\s)(href|src)="([^"]*)"/g, (whole, space, attr, url) => `${space}${attr}="${rewrite(url)}"`)
    .replace(/url\("([^"]*)"\)/g, (whole, url) => `url("${rewrite(url)}")`);
}

function renderLanguage(source, page, language, translations, version) {
  const config = LANGUAGES[language];
  const strings = translations[language];
  const missing = [];
  const notice = generatedNotice(page.source);
  let html = source;

  // 冪等にするため、前回の生成通知を取り除いてから処理する
  html = html.replace(notice, '');

  // <html lang>, <title>
  html = replaceOnce(html, /<html lang="[^"]*">/, `<html lang="${language}">`, '<html lang>');
  html = replaceOnce(html, /<title>[^<]*<\/title>/, `<title>${escapeText(strings.metaTitle)}</title>`, '<title>');

  // メタデータ
  html = setMetaContent(html, 'name="description"', strings.metaDescription);
  html = setMetaContent(html, 'property="og:title"', strings.metaTitle);
  html = setMetaContent(html, 'property="og:description"', strings.metaDescription);
  html = setMetaContent(html, 'property="og:url"', pageUrl(page, language));
  html = setMetaContent(html, 'property="og:locale"', config.locale);
  html = setMetaContent(html, 'property="og:locale:alternate"', config.alternateLocale);
  html = setMetaContent(html, 'name="twitter:title"', strings.metaTitle);
  html = setMetaContent(html, 'name="twitter:description"', strings.metaDescription);

  // canonical / hreflang（ja が既定 = x-default）
  html = setLinkHref(html, 'rel="canonical"', pageUrl(page, language));
  html = setLinkHref(html, 'rel="alternate" hreflang="ja"', pageUrl(page, 'ja'));
  html = setLinkHref(html, 'rel="alternate" hreflang="en"', pageUrl(page, 'en'));
  html = setLinkHref(html, 'rel="alternate" hreflang="x-default"', pageUrl(page, 'ja'));

  // JSON-LD（ランディングのみ）: url / inLanguage / softwareVersion（package.json と同期）
  if (html.includes('application/ld+json')) {
    const siteUrlPattern = SITE_URL.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
    html = replaceOnce(html, new RegExp(`("url": ")${siteUrlPattern}(?:en\\/)?(",\\n {4}"applicationCategory")`),
      `$1${pageUrl(page, language)}$2`, 'JSON-LD url');
    html = replaceOnce(html, /("softwareVersion": ")[^"]*(")/, `$1${version}$2`, 'JSON-LD softwareVersion');
    if (/"inLanguage": "[^"]*"/.test(html)) {
      html = html.replace(/"inLanguage": "[^"]*"/, `"inLanguage": "${language}"`);
    } else {
      html = replaceOnce(html, /(\n {4}"softwareVersion": "[^"]*",)/, `$1\n    "inLanguage": "${language}",`, 'JSON-LD softwareVersion line');
    }
  }

  // 本文
  html = replaceElementContents(html, 'data-i18n', strings, escapeText, missing);
  html = replaceElementContents(html, 'data-i18n-html', strings, (value) => String(value), missing);
  html = replaceAriaLabels(html, strings, missing);

  // 言語ボタン: 状態と移動先
  html = html.replace(/<button[^<>]*\sdata-lang-button="(ja|en)"[^<>]*>/g, (whole, buttonLanguage) => {
    const active = buttonLanguage === language;
    return `<button type="button" data-lang-button="${buttonLanguage}" data-lang-href="${languageButtonHref(page, language, buttonLanguage)}" aria-pressed="${active}"${active ? ' class="active"' : ''}>`;
  });

  // ページ内 JS の既定言語
  html = replaceOnce(html, /\n {4}let lang = "(?:ja|en)";\n/, `\n    let lang = "${language}";\n`, 'let lang');

  // 生成先から解決できる相対パス
  html = rewriteRelativeUrls(html, page, language);

  // 生成物には doctype 直後に通知コメントを置く（doctype より前に置くと一部のバリデータが警告する）
  if (outputFile(page, language) !== page.source) {
    html = replaceOnce(html, /^(<!doctype html>\n)/i, `$1${notice}`, '<!doctype html>');
  }

  return { html, missing: Array.from(new Set(missing)) };
}

/**
 * 生成結果を返す（書き込みはしない）。
 *
 * `options.source` / `options.sources` でソースの内容を差し替えられる（テスト用。source は index.html）。
 * `translations` は index.html の辞書、`pageTranslations` はページ（ソースのパス）ごとの辞書。
 * `missing` は全ページを通した、辞書に無いキー。
 */
export function buildLandingPages(options = {}) {
  const root = options.root || ROOT;
  const sources = { ...options.sources };
  if (options.source !== undefined) sources[SOURCE_FILE] = options.source;
  const version = options.version || JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
  const outputs = {};
  const missing = { ja: [], en: [] };
  const pageTranslations = {};
  for (const page of PAGES) {
    const source = sources[page.source] !== undefined ? sources[page.source] : fs.readFileSync(path.join(root, page.source), 'utf8');
    const translations = extractTranslations(source, page.source);
    pageTranslations[page.source] = translations;
    for (const language of Object.keys(LANGUAGES)) {
      const result = renderLanguage(source, page, language, translations, version);
      outputs[outputFile(page, language)] = result.html;
      missing[language] = Array.from(new Set([...missing[language], ...result.missing]));
    }
  }
  return { outputs, missing, version, translations: pageTranslations[SOURCE_FILE], pageTranslations };
}

function main(argv) {
  const check = argv.includes('--check');
  const { outputs, missing } = buildLandingPages();
  let changed = 0;
  for (const [file, html] of Object.entries(outputs)) {
    const target = path.join(ROOT, file);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (current === html) continue;
    changed += 1;
    if (check) {
      console.error(`[build-landing] ${file} is out of date. Run \`npm run build:site\` and commit the result.`);
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, html);
      console.log(`[build-landing] wrote ${file}`);
    }
  }
  for (const [language, keys] of Object.entries(missing)) {
    if (keys.length) console.warn(`[build-landing] translations.${language} lacks: ${keys.join(', ')}`);
  }
  if (check && changed) process.exit(1);
  if (!changed) console.log('[build-landing] up to date');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
